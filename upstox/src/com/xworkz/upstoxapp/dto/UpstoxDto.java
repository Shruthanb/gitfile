package com.xworkz.upstoxapp.dto;

public class UpstoxDto {
    private String fullName;
    private String mobile;
    private String email;
    private String dob;
    private String panNumber;
    private String loginId;
    private String password;
    private String confirmPassword;
    private String brokeragePlan;
    private String nomineeName;

    public void setFullName(String fullName) {
        this.fullName = fullName;
    }
    public String getFullName() {
        return fullName;
    }

    public void setMobile(String mobile) {
        this.mobile = mobile;
    }
    public String getMobile() {
        return mobile;
    }

    public void setEmail(String email) {
        this.email = email;
    }
    public String getEmail() {
        return email;
    }

    public void setDob(String dob) {
        this.dob = dob;
    }
    public String getDob() {
        return dob;
    }

    public void setPanNumber(String panNumber) {
        this.panNumber = panNumber;
    }
    public String getPanNumber() {
        return panNumber;
    }

    public void setLoginId(String loginId) {
        this.loginId = loginId;
    }
    public String getLoginId() {
        return loginId;
    }

    public void setPassword(String password) {
        this.password = password;
    }
    public String getPassword() {
        return password;
    }

    public void setConfirmPassword(String confirmPassword) {
        this.confirmPassword = confirmPassword;
    }
    public String getConfirmPassword() {
        return confirmPassword;
    }

    public void setBrokeragePlan(String brokeragePlan) {
        this.brokeragePlan = brokeragePlan;
    }
    public String getBrokeragePlan() {
        return brokeragePlan;
    }

    public void setNomineeName(String nomineeName) {
        this.nomineeName = nomineeName;
    }
    public String getNomineeName() {
        return nomineeName;
    }
}
